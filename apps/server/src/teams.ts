type Cell = unknown;

/** Pure: Airtable record fields (by field id) → team office zone id, or "". */
export function roomForRecord(fields: Record<string, Cell>): string {
  const links = [...asIds(fields[F.sales]), ...asIds(fields[F.marketing])];
  for (const id of links) if (TEAM_ROOMS[id]) return TEAM_ROOMS[id];
  const areas = [...asNames(fields[F.area]), ...asNames(fields[F.areaLookup])].map((a) => a.trim().toLowerCase());
  for (const a of areas) if (AREA_ROOMS[a]) return AREA_ROOMS[a];
  return "";
}

function asIds(v: Cell): string[] {
  if (!Array.isArray(v)) return [];
  return v.map((x) => (typeof x === "string" ? x : (x as { id?: string })?.id ?? "")).filter(Boolean);
}

function asNames(v: Cell): string[] {
  if (typeof v === "string") return [v];
  if (Array.isArray(v)) return v.flatMap(asNames);
  if (v && typeof v === "object" && typeof (v as { name?: unknown }).name === "string") return [(v as { name: string }).name];
  return [];
}

// ---- Roster cache --------------------------------------------------------
let roster = new Map<string, string>(); // email → zone
let fetchedAt = 0;
let inflight: Promise<void> | null = null;
const TTL_MS = 10 * 60 * 1000;

async function refresh(): Promise<void> {
  const token = process.env.AIRTABLE_TOKEN;
  if (!token) return;
  const base = process.env.AIRTABLE_BASE_ID ?? "appL1aq6ivn3D2OaC";
  const table = process.env.AIRTABLE_USERS_TABLE ?? "tblUcciENqoEXtVEu";
  const next = new Map<string, string>();
  let offset = "";
  do {
    const q = new URLSearchParams({ returnFieldsByFieldId: "true", pageSize: "100" });
    for (const f of Object.values(F)) q.append("fields[]", f);
    if (offset) q.set("offset", offset);
    const res = await fetch(`https://api.airtable.com/v0/${base}/${table}?${q}`, {
      headers: { Authorization: `Bearer ${token}` },
    });
    if (!res.ok) throw new Error(`airtable ${res.status}`);
    const body = (await res.json()) as { records: { fields: Record<string, Cell> }[]; offset?: string };
    for (const r of body.records) {
      if (r.fields[F.active] !== true) continue;
      const email = typeof r.fields[F.email] === "string" ? (r.fields[F.email] as string).trim().toLowerCase() : "";
      const zone = roomForRecord(r.fields);
      if (email && zone) next.set(email, zone);
    }
    offset = body.offset ?? "";
  } while (offset);
  roster = next;
  fetchedAt = Date.now();
  console.log(`[teams] ${roster.size} personas con oficina de equipo (Airtable)`);
}

/** Team office of a person ("" if unknown or Airtable is not configured). */
export async function teamRoomOf(email: string): Promise<string> {
  if (!process.env.AIRTABLE_TOKEN) return "";
  if (Date.now() - fetchedAt > TTL_MS) {
    inflight ??= refresh()
      .catch((e) => console.error("[teams] airtable sync failed:", e))
      .finally(() => (inflight = null));
    await inflight;
  }
  return roster.get(email.trim().toLowerCase()) ?? "";
}

// ---- Desks per office (generated by scripts/gen-map.mjs) -----------------
export interface DeskSpot {
  deskId: number;
  zone: string;
  color: string;
}

let spots: DeskSpot[] | null = null;

export function deskSpots(): DeskSpot[] {
  if (spots) return spots;
  const candidates = [
    path.resolve(process.cwd(), "..", "..", "apps", "web", "public", "desks.json"),
    path.resolve(process.cwd(), "apps", "web", "public", "desks.json"),
  ];
  const file = candidates.find((c) => existsSync(c));
  try {
    spots = file ? (JSON.parse(readFileSync(file, "utf8")) as DeskSpot[]) : [];
  } catch {
    spots = [];
  }
  return spots;
}

/** First free desk of a team office (lowest id = closest to the door row). */
export function freeDeskIn(zone: string, taken: Set<number>, list = deskSpots()): DeskSpot | null {
  return list.filter((d) => d.zone === zone && !taken.has(d.deskId)).sort((a, b) => a.deskId - b.deskId)[0] ?? null;
}
